import AppKit
import ApplicationServices
import Foundation

public enum InsertResult: Equatable, Sendable {
    case accessibility   // written directly into the field
    case pasted          // clipboard + ⌘V
    case copiedOnly      // no editable field; text left on the clipboard
    case focusChanged    // the user switched apps meanwhile; text left on the clipboard
    case blocked         // password field or excluded app; nothing typed, nothing copied
}

/// Puts text where the user is typing: write through Accessibility, check it landed, fall back to a
/// clipboard paste, and if there is no text field, leave it on the clipboard.
///
/// Safety rules: never type into password fields or excluded apps; never type into a different app
/// than the one the dictation started in; strip control characters; never insert a newline into a
/// terminal (it would run a command).
@MainActor
public enum TextInserter {
    /// Apps where Accessibility writes are unreliable or bypass the editor; paste straight away.
    static let pasteFirst: Set<String> = [
        "com.apple.Terminal", "com.googlecode.iterm2", "dev.warp.Warp-Stable", "com.mitchellh.ghostty",
        "com.microsoft.VSCode", "com.todesktop.230313mzl4w4u92", "com.exafunction.windsurf", "com.tinyspeck.slackmacgap",
        "com.hnc.Discord", "notion.id", "com.microsoft.Word", "net.whatsapp.WhatsApp", "desktop.WhatsApp",
    ]

    /// Pasteboard types that tell clipboard managers to ignore a temporary item
    /// (convention from nspasteboard.org, honoured by most clipboard history apps).
    static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Adds a space when the cursor sits right after a word.
    public static func withLeadingSpace(_ text: String, beforeCursor: String) -> String {
        guard let last = beforeCursor.last, let first = text.first else { return text }
        if last.isWhitespace || "([{\"'“‘/@#".contains(last) { return text }
        if ".,!?;:)]}".contains(first) || first.isWhitespace || first.isNewline { return text }
        return " " + text
    }

    /// True when the app that has focus now is the one the dictation started in.
    public static func focusUnchanged(since context: TypingContext) -> Bool {
        guard context.pid != 0 else { return true }
        return NSWorkspace.shared.frontmostApplication?.processIdentifier == context.pid
    }

    /// True when the field that has focus now must not receive text: a password field, an excluded app,
    /// or macOS secure input (password prompts, Terminal's Secure Keyboard Entry).
    public static func focusIsProtected() -> Bool {
        if OutputSafety.secureInputActive() { return true }
        if let bundle = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, OutputSafety.isExcluded(bundleID: bundle) { return true }
        if let element = ContextReader.focusedElement(), ContextReader.isSecure(element) { return true }
        return false
    }

    public static func insert(_ text: String, context: TypingContext) async -> InsertResult {
        if context.isSecure || OutputSafety.isExcluded(bundleID: context.bundleID) || focusIsProtected() { return .blocked }
        let clean = OutputSafety.sanitize(text, forTerminal: OutputSafety.isTerminal(bundleID: context.bundleID))
        guard !clean.isEmpty else { return .copiedOnly }
        guard focusUnchanged(since: context) else {
            copyToClipboard(clean)
            return .focusChanged
        }
        if !context.isEditable && context.role.isEmpty {
            copyToClipboard(clean)
            return .copiedOnly
        }
        let final = withLeadingSpace(clean, beforeCursor: context.beforeCursor)
        if context.isEditable, !pasteFirst.contains(context.bundleID),
           let element = ContextReader.focusedElement(), await writeThroughAccessibility(final, element: element) {
            return .accessibility
        }
        if context.isEditable || !context.role.isEmpty {
            await paste(final)
            return .pasted
        }
        copyToClipboard(clean)
        return .copiedOnly
    }

    /// Replaces the whole field value (Command Mode with no selection). Same safety rules as `insert`.
    public static func replaceAll(_ text: String, context: TypingContext) async -> InsertResult {
        if context.isSecure || OutputSafety.isExcluded(bundleID: context.bundleID) || focusIsProtected() { return .blocked }
        let clean = OutputSafety.sanitize(text, forTerminal: OutputSafety.isTerminal(bundleID: context.bundleID))
        guard focusUnchanged(since: context) else {
            copyToClipboard(clean)
            return .focusChanged
        }
        guard let element = ContextReader.focusedElement() else { return .copiedOnly }
        if ContextReader.isSettable(element, kAXValueAttribute),
           AXUIElementSetAttributeValue(element, kAXValueAttribute as CFString, clean as CFString) == .success {
            try? await Task.sleep(for: .milliseconds(60))
            if ContextReader.value(of: element) == clean { return .accessibility }
        }
        // Select all, then paste over it.
        postKey(0, flags: .maskCommand) // ⌘A
        try? await Task.sleep(for: .milliseconds(60))
        await paste(clean)
        return .pasted
    }

    static func writeThroughAccessibility(_ text: String, element: AXUIElement) async -> Bool {
        let before = ContextReader.value(of: element)
        guard AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success else { return false }
        try? await Task.sleep(for: .milliseconds(60))
        // Some apps report success without changing anything. Trust it only if the value changed
        // and now contains the text.
        guard let after = ContextReader.value(of: element) else { return false }
        return after != before && after.contains(text.trimmingCharacters(in: .whitespaces))
    }

    // MARK: Clipboard

    /// Leaves text on the clipboard for the user to paste (a deliberate copy, so it is not marked transient).
    public static func copyToClipboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// Everything currently on the clipboard, so it can be put back exactly.
    public static func saveClipboard() -> [[(NSPasteboard.PasteboardType, Data)]] {
        NSPasteboard.general.pasteboardItems?.map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        } ?? []
    }

    public static func restoreClipboard(_ saved: [[(NSPasteboard.PasteboardType, Data)]]) {
        let pb = NSPasteboard.general
        pb.clearContents()
        // A password manager marks copied secrets as concealed and clears them itself.
        // Putting one back would undo that, so it is dropped instead.
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        if saved.contains(where: { $0.contains { $0.0 == concealed } }) { return }
        let items = saved.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    /// Pastes `text` with ⌘V, then restores whatever was on the clipboard. The temporary item stays on
    /// this Mac (not synced by Universal Clipboard) and is marked so clipboard managers skip it.
    public static func paste(_ text: String) async {
        let pb = NSPasteboard.general
        let saved = saveClipboard()
        pb.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setData(Data(), forType: type) }
        pb.writeObjects([item])
        let changeCount = pb.changeCount

        postKey(9, flags: .maskCommand) // ⌘V
        // Slow apps read the clipboard late; restoring too early would paste the old contents.
        try? await Task.sleep(for: .milliseconds(500))

        // Restore only if nothing else used the clipboard meanwhile.
        guard pb.changeCount == changeCount else { return }
        restoreClipboard(saved)
    }

    static func postKey(_ keyCode: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        down?.flags = flags
        up?.flags = flags
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
